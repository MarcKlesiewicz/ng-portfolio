import { readFile, readdir, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const booksDirectory = resolve(projectRoot, 'src/assets/images/books_2026');
const manifestPath = resolve(projectRoot, 'src/app/off-topic/data/books-2026.generated.ts');
const supportedBookFile = /^[sabcdf]_\d+\.(?:avif|jpe?g|png|webp)$/i;

const files = (await readdir(booksDirectory, { withFileTypes: true }))
  .filter((entry) => entry.isFile() && supportedBookFile.test(entry.name))
  .map((entry) => entry.name)
  .sort((left, right) => left.localeCompare(right, 'en', { numeric: true }));

const fileEntries = files.map((file) => `'${file}'`).join(', ');
const manifest = `// Generated by scripts/generate-book-tier-manifest.mjs. Do not edit manually.\nexport const BOOKS_2026_FILES = [${fileEntries}] as const;\n`;

let existingManifest = '';

try {
  existingManifest = await readFile(manifestPath, 'utf8');
} catch (error) {
  if (error.code !== 'ENOENT') {
    throw error;
  }
}

if (existingManifest !== manifest) {
  await writeFile(manifestPath, manifest, 'utf8');
}
